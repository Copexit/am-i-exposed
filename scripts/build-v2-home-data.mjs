#!/usr/bin/env node
/**
 * Compacts the real WabiSabi CoinJoin test fixture into the tiny module that
 * feeds the v2 home hero ("Glass Mempool"). Only values and script types are
 * kept; every label on screen is derived from these at runtime
 * (src/components/v2/home/field-labels.ts), so nothing is invented.
 *
 *   node scripts/build-v2-home-data.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "src/lib/analysis/heuristics/__tests__/fixtures/api-responses/wabisabi-coinjoin.json");
const out = join(root, "src/components/v2/home/field-data.ts");

const tx = JSON.parse(readFileSync(src, "utf8"));
// One char per script type keeps the module small. Unknown types fail loudly.
const CODE = { v0_p2wpkh: "w", v1_p2tr: "t", v0_p2wsh: "s", p2sh: "h", p2pkh: "k" };
const code = (t) => {
  if (!CODE[t]) throw new Error(`unmapped script type ${t}`);
  return CODE[t];
};

const inValues = tx.vin.map((v) => v.prevout.value);
const inTypes = tx.vin.map((v) => code(v.prevout.scriptpubkey_type)).join("");
const outValues = tx.vout.map((v) => v.value);
const outTypes = tx.vout.map((v) => code(v.scriptpubkey_type)).join("");

const body = `// GENERATED by scripts/build-v2-home-data.mjs from the wabisabi-coinjoin.json
// test fixture. Do not edit by hand.

/** Script type codes used in the *Types strings below. */
export const SCRIPT_CODES = ${JSON.stringify(Object.fromEntries(Object.entries(CODE).map(([k, v]) => [v, k])))} as const;

export interface FieldTx {
  txid: string;
  inValues: readonly number[];
  inTypes: string;
  outValues: readonly number[];
  outTypes: string;
}

export const FIELD_TX: FieldTx = {
  txid: ${JSON.stringify(tx.txid)},
  inValues: ${JSON.stringify(inValues)},
  inTypes: ${JSON.stringify(inTypes)},
  outValues: ${JSON.stringify(outValues)},
  outTypes: ${JSON.stringify(outTypes)},
};
`;
writeFileSync(out, body);
console.log(`wrote ${out} (${body.length} bytes, ${inValues.length} in / ${outValues.length} out)`);
